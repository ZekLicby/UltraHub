const word = (
  japanese: string,
  romanization: string,
  meaning: string,
  type: WordType,
  accepted?: Partial<Record<WordMode, string[]>>,
): Word => ({
  japanese,
  romanization,
  meaning,
  type,
  acceptedAnswers: {
    sound: accepted?.sound ?? [romanization],
    meaning: accepted?.meaning ?? [meaning],
  },
})

