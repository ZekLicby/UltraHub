export type WordType = 'noun' | 'verb' | 'adjective' | 'pronoun' | 'adverb' | 'other'

export type WordMode = 'sound' | 'meaning'

export interface Word {
  japanese: string
  romanization: string
  meaning: string
  type: WordType
  acceptedAnswers: Record<WordMode, string[]>
}

export interface WordCategory {
  id: WordType
  label: string
  sample: string
}

